import { useState, useEffect, useCallback } from "react";
import {
  History, Clock, CheckCircle2, Send, Eye, ChevronDown, ChevronRight,
  RefreshCw, Loader2, AlertTriangle, FileText, User, ArrowRight,
} from "lucide-react";
import { tournamentStageService } from "../../../../services/sports/tournamentStageService";
import { showError } from "../../../../utils/ToastUtils";
import type { ScheduleVersion, ScheduleVersionStatus } from "../../../../types/tournamentStage";

const VERSION_STATUS_STYLES: Record<ScheduleVersionStatus, { bg: string; text: string }> = {
  DRAFT: { bg: "bg-amber-50", text: "text-amber-700" },
  VALIDATED: { bg: "bg-blue-50", text: "text-blue-700" },
  APPROVED: { bg: "bg-indigo-50", text: "text-indigo-700" },
  PUBLISHED: { bg: "bg-emerald-50", text: "text-emerald-700" },
  SUPERSEDED: { bg: "bg-slate-100", text: "text-slate-500" },
};

function formatDateTime(iso: string | null | undefined): string {
  if (!iso) return "—";
  try {
    return new Date(iso).toLocaleString("en-IN", {
      day: "2-digit", month: "short", year: "numeric",
      hour: "2-digit", minute: "2-digit", hour12: true,
    });
  } catch { return iso; }
}

function VersionRow({ version, isExpanded, onToggle }: {
  version: ScheduleVersion;
  isExpanded: boolean;
  onToggle: () => void;
}) {
  const style = VERSION_STATUS_STYLES[version.status] || VERSION_STATUS_STYLES.DRAFT;
  return (
    <div className="border border-slate-50 rounded-lg overflow-hidden">
      <button
        className="w-full flex items-center gap-3 p-3 text-left hover:bg-slate-50/50 transition-colors cursor-pointer"
        onClick={onToggle}
      >
        <div className="flex-shrink-0 text-slate-400">
          {isExpanded ? <ChevronDown className="w-3 h-3" /> : <ChevronRight className="w-3 h-3" />}
        </div>
        <div className="flex-shrink-0 w-8 h-8 rounded-lg bg-indigo-50 text-indigo-600 flex items-center justify-center text-[10px] font-bold">
          v{version.versionNumber}
        </div>
        <div className="flex-1 min-w-0">
          <div className="flex items-center gap-2">
            <span className={`${style.bg} ${style.text} px-1.5 py-0.5 rounded text-[8px] font-bold uppercase tracking-wider`}>
              {version.status}
            </span>
            {version.changeReason && (
              <span className="text-[9px] text-slate-500 truncate">{version.changeReason}</span>
            )}
          </div>
          <div className="flex items-center gap-3 mt-0.5 text-[9px] text-slate-500">
            <span className="flex items-center gap-0.5">
              <Clock className="w-2.5 h-2.5" />
              {formatDateTime(version.createdAt)}
            </span>
            {version.changedMatchIds.length > 0 && (
              <span>{version.changedMatchIds.length} match(es) changed</span>
            )}
          </div>
        </div>
      </button>

      {isExpanded && (
        <div className="px-4 pb-3 pt-1 border-t border-slate-50 space-y-2">
          <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
            {version.generatedBy && (
              <div className="bg-slate-50 rounded-lg p-2">
                <div className="text-[8px] text-slate-500 uppercase tracking-wider">Generated by</div>
                <div className="text-[10px] font-semibold text-slate-700 flex items-center gap-1">
                  <User className="w-2.5 h-2.5" /> {version.generatedBy}
                </div>
              </div>
            )}
            {version.approvedBy && (
              <div className="bg-slate-50 rounded-lg p-2">
                <div className="text-[8px] text-slate-500 uppercase tracking-wider">Approved by</div>
                <div className="text-[10px] font-semibold text-slate-700 flex items-center gap-1">
                  <CheckCircle2 className="w-2.5 h-2.5" /> {version.approvedBy}
                </div>
                <div className="text-[8px] text-slate-400">{formatDateTime(version.approvedAt)}</div>
              </div>
            )}
            {version.publishedBy && (
              <div className="bg-slate-50 rounded-lg p-2">
                <div className="text-[8px] text-slate-500 uppercase tracking-wider">Published by</div>
                <div className="text-[10px] font-semibold text-slate-700 flex items-center gap-1">
                  <Send className="w-2.5 h-2.5" /> {version.publishedBy}
                </div>
                <div className="text-[8px] text-slate-400">{formatDateTime(version.publishedAt)}</div>
              </div>
            )}
          </div>

          {version.changedMatchIds.length > 0 && (
            <div className="bg-amber-50/50 rounded-lg p-2">
              <div className="text-[8px] text-amber-700 font-semibold uppercase tracking-wider mb-1">Changed Matches</div>
              <div className="flex flex-wrap gap-1">
                {version.changedMatchIds.map(id => (
                  <span key={id} className="bg-amber-100 text-amber-800 px-1.5 py-0.5 rounded text-[8px] font-mono">
                    #{id}
                  </span>
                ))}
              </div>
            </div>
          )}

          {version.changedFields.length > 0 && (
            <div className="bg-slate-50 rounded-lg p-2">
              <div className="text-[8px] text-slate-600 font-semibold uppercase tracking-wider mb-1">Changed Fields</div>
              <div className="space-y-1">
                {version.changedFields.map((cf, i) => (
                  <div key={i} className="flex items-center gap-1 text-[9px]">
                    {Object.entries(cf).map(([field, value]) => (
                      <span key={field} className="text-slate-600">
                        <span className="font-semibold">{field}:</span> {value}
                      </span>
                    ))}
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

export function ScheduleVersionHistory({
  configId,
  stageId,
}: {
  configId: number;
  stageId?: number;
}) {
  const [versions, setVersions] = useState<ScheduleVersion[]>([]);
  const [loading, setLoading] = useState(true);
  const [expandedId, setExpandedId] = useState<number | null>(null);

  const fetchVersions = useCallback(async () => {
    setLoading(true);
    try {
      const data = await tournamentStageService.getScheduleVersions(configId, stageId);
      setVersions(data);
    } catch {
      showError("Failed to load schedule history");
    } finally {
      setLoading(false);
    }
  }, [configId, stageId]);

  useEffect(() => { fetchVersions(); }, [fetchVersions]);

  if (loading) {
    return (
      <div className="flex items-center justify-center py-8">
        <Loader2 className="w-4 h-4 animate-spin text-indigo-400" />
        <span className="text-[10px] ml-2 text-slate-500">Loading history…</span>
      </div>
    );
  }

  if (versions.length === 0) {
    return (
      <div className="bg-white rounded-xl border border-slate-100 shadow-sm p-6 text-center space-y-2">
        <History className="w-8 h-8 text-slate-300 mx-auto" />
        <p className="text-[10px] text-slate-500">No schedule versions yet</p>
      </div>
    );
  }

  return (
    <div className="space-y-3">
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2">
          <History className="w-4 h-4 text-slate-500" />
          <span className="text-xs font-bold text-slate-800">Schedule History</span>
          <span className="text-[9px] text-slate-400">{versions.length} version{versions.length !== 1 ? "s" : ""}</span>
        </div>
        <button
          onClick={fetchVersions}
          className="p-1.5 rounded-lg hover:bg-slate-100 text-slate-400 hover:text-slate-600 cursor-pointer"
        >
          <RefreshCw className="w-3.5 h-3.5" />
        </button>
      </div>

      <div className="bg-white rounded-xl border border-slate-100 shadow-sm p-2 space-y-1">
        {versions
          .sort((a, b) => b.versionNumber - a.versionNumber)
          .map(v => (
            <VersionRow
              key={v.id}
              version={v}
              isExpanded={expandedId === v.id}
              onToggle={() => setExpandedId(expandedId === v.id ? null : v.id)}
            />
          ))}
      </div>
    </div>
  );
}
